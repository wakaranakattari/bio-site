import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = join(root, 'public/writing/index.json');
const out = join(root, 'src/bio_site/data/articles.cljs');

const items = JSON.parse(readFileSync(manifest, 'utf8'));
const fields = ['slug', 'title', 'category', 'date', 'summary'];

const entries = items.map((it) => {
  const kvs = fields
    .filter((k) => it[k] != null && it[k] !== '')
    .map((k) => `:${k} ${JSON.stringify(String(it[k]))}`)
    .join(' ');
  return `  {${kvs}}`;
});

const content = `;; @file    <data/articles.cljs>
;; @author  <wakaranakattari@gmail.com>
;; @info    <generated by scripts/gen-articles.mjs, do not edit>
;; @version <1.0>

;; @secstart->@secname <ns>
(ns bio-site.data.articles)
;; @secend->@secname   <ns>

;; @secstart->@secname <articles>
  ;; @funcinfo <articles manifest, embedded at build time>
(def articles
  [${entries.join('\n')}])
;; @secend->@secname   <articles>
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, content);
console.log('gen-articles: wrote', entries.length, 'articles');
